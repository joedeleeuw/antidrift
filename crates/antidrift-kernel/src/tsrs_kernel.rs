use tsrs_ast::{self as ast, Kind, Node, SourceFile};
use tsrs_core::P;
use tsrs_core::tspath;
use tsrslint::utils::trim_node_text_range;

#[must_use]
pub fn normalize_path(file_path: &str) -> String {
    tspath::normalize_slashes(file_path)
}

#[must_use]
pub fn is_declaration_file(file_path: &str) -> bool {
    let normalized = normalize_path(file_path);
    normalized.ends_with(".d.ts")
        || normalized.ends_with(".d.mts")
        || normalized.ends_with(".d.cts")
}

fn has_script_ext(file_path: &str) -> bool {
    const EXTS: &[&str] = &[".ts", ".tsx", ".js", ".jsx", ".mts", ".cts", ".mjs", ".cjs"];
    EXTS.iter().any(|ext| file_path.ends_with(ext))
}

fn strip_script_ext(file_path: &str) -> Option<&str> {
    const EXTS: &[&str] = &[".tsx", ".jsx", ".mts", ".cts", ".mjs", ".cjs", ".ts", ".js"];
    for ext in EXTS {
        if let Some(stem) = file_path.strip_suffix(ext) {
            return Some(stem);
        }
    }
    None
}

fn path_has_dir_segment(normalized: &str, segments: &[&str]) -> bool {
    normalized.split('/').any(|part| segments.contains(&part))
}

fn path_matches_dir_or_stem(normalized: &str, segments: &[&str]) -> bool {
    if path_has_dir_segment(normalized, segments) {
        return true;
    }
    let Some(stem) = strip_script_ext(normalized) else {
        return false;
    };
    let last = stem.rsplit('/').next().unwrap_or(stem);
    segments.contains(&last)
}

#[must_use]
pub fn is_generated_file(file_path: &str, source_text: &str) -> bool {
    let normalized = normalize_path(file_path);
    if is_declaration_file(&normalized) {
        return true;
    }
    if path_has_dir_segment(
        &normalized,
        &[
            "__generated__",
            "generated",
            "_generated",
            "gen",
            "dist",
            "build",
            ".next",
        ],
    ) {
        return true;
    }
    if let Some(stem) = strip_script_ext(&normalized)
        && (stem.ends_with(".gen")
            || stem.ends_with(".generated")
            || stem.ends_with(".pb")
            || stem.ends_with(".d"))
    {
        return true;
    }
    let prefix_len = source_text.len().min(512);
    let header_lower = source_text
        .get(..prefix_len)
        .unwrap_or(source_text)
        .to_ascii_lowercase();
    header_lower.contains("@generated")
        || header_lower.contains("do not edit")
        || header_lower.contains("auto-generated")
        || header_lower.contains("code generated by")
}

#[must_use]
pub fn is_test_file(file_path: &str) -> bool {
    let normalized = normalize_path(file_path);
    if path_has_dir_segment(
        &normalized,
        &[
            "test",
            "tests",
            "__tests__",
            "__mocks__",
            "fixtures",
            "__fixtures__",
        ],
    ) {
        return true;
    }
    let Some(stem) = strip_script_ext(&normalized) else {
        return false;
    };
    stem.ends_with(".test")
        || stem.ends_with(".spec")
        || stem.ends_with(".fixture")
        || stem.ends_with(".mock")
}

