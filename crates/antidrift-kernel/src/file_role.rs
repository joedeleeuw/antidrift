use tsrs_ast::SourceFile;
use tsrs_core::P;
use tsrs_core::tspath;

use crate::tsrs_kernel::normalize_path;

#[must_use]
pub fn is_declaration_file(file_path: &str) -> bool {
    tspath::is_declaration_file_name(&normalize_path(file_path))
}

fn has_script_ext(file_path: &str) -> bool {
    tspath::has_ts_file_extension(file_path) || tspath::has_js_file_extension(file_path)
}

fn strip_script_ext(file_path: &str) -> Option<&str> {
    has_script_ext(file_path).then(|| tspath::remove_file_extension(file_path))
}

fn path_has_dir_segment(normalized: &str, segments: &[&str]) -> bool {
    normalized.split('/').any(|part| segments.contains(&part))
}

fn path_matches_dir_or_stem(normalized: &str, segments: &[&str]) -> bool {
    if path_has_dir_segment(normalized, segments) {
        return true;
    }
    let Some(stem) = strip_script_ext(normalized) else {
        return false;
    };
    let last = stem.rsplit('/').next().unwrap_or(stem);
    segments.contains(&last)
}

const GENERATED_DIRS: &[&str] = &[
    "__generated__",
    "generated",
    "_generated",
    "gen",
    "dist",
    "build",
    ".next",
];
const BOUNDARY_SEGMENTS: &[&str] = &[
    "route",
    "routes",
    "controller",
    "controllers",
    "handler",
    "handlers",
    "adapter",
    "adapters",
    "gateway",
    "gateways",
    "client",
    "clients",
    "parser",
    "parsers",
    "decoder",
    "decoders",
    "boundaries",
    "boundary",
    "api",
    "rpc",
    "trpc",
    "orpc",
    "webhook",
    "ingest",
    "cli",
];
const DOMAIN_SEGMENTS: &[&str] = &[
    "domain",
    "model",
    "models",
    "entities",
    "core",
    "contract",
    "contracts",
    "schema",
    "schemas",
];

#[must_use]
pub fn is_generated_file(file_path: &str, source_text: &str) -> bool {
    let normalized = normalize_path(file_path);
    if path_has_dir_segment(&normalized, GENERATED_DIRS) {
        return true;
    }
    if let Some(stem) = strip_script_ext(&normalized)
        && (stem.ends_with(".gen") || stem.ends_with(".generated") || stem.ends_with(".pb"))
    {
        return true;
    }
    let prefix_len = source_text.len().min(512);
    let header_lower = source_text
        .get(..prefix_len)
        .unwrap_or(source_text)
        .to_ascii_lowercase();
    header_lower.contains("@generated")
        || header_lower.contains("do not edit")
        || header_lower.contains("auto-generated")
        || header_lower.contains("code generated by")
}

#[must_use]
pub fn is_test_or_spec_file(file_path: &str) -> bool {
    let normalized = normalize_path(file_path);
    path_has_dir_segment(&normalized, &["test", "tests", "__tests__"])
        || strip_script_ext(&normalized)
            .is_some_and(|stem| stem.ends_with(".test") || stem.ends_with(".spec"))
}

#[must_use]
pub fn is_test_file(file_path: &str) -> bool {
    if is_test_or_spec_file(file_path) {
        return true;
    }
    let normalized = normalize_path(file_path);
    path_has_dir_segment(&normalized, &["__mocks__", "fixtures", "__fixtures__"])
        || strip_script_ext(&normalized)
            .is_some_and(|stem| stem.ends_with(".fixture") || stem.ends_with(".mock"))
}

#[must_use]
pub fn is_authored_source_file(sf: P<SourceFile>) -> bool {
    let file_name = sf.file_name();
    !is_declaration_file(file_name)
        && !is_test_file(file_name)
        && !is_generated_file(file_name, sf.text())
}

#[must_use]
pub fn is_boundary_file(file_path: &str) -> bool {
    let normalized = normalize_path(file_path);
    has_script_ext(&normalized) && path_matches_dir_or_stem(&normalized, BOUNDARY_SEGMENTS)
}

#[must_use]
pub fn is_domain_file(file_path: &str) -> bool {
    let normalized = normalize_path(file_path);
    has_script_ext(&normalized) && path_matches_dir_or_stem(&normalized, DOMAIN_SEGMENTS)
}
