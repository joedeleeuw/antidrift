function assertReported(messages, expected, hostLabel) {
  for (const { ruleId, message } of expected) {
    assert.ok(
      messages.some(
        (diagnostic) =>
          diagnostic.ruleId === ruleId && diagnostic.message === message
      ),
      `Expected ${hostLabel} ${ruleId}: ${message}; got ${JSON.stringify(messages)}`
    );
  }
}

function writeTypedProject(workDir, repoRoot) {
  writeFileSync(
    join(workDir, "tsconfig.json"),
    JSON.stringify({
      compilerOptions: {
        strict: true,
        target: "ES2022",
        module: "ESNext",
        moduleResolution: "Bundler",
        jsx: "preserve",
        skipLibCheck: true,
        noEmit: true,
      },
      include: ["*.ts", "*.tsx", "_generated/**/*.d.ts"],
    }),
    "utf8"
  );
  mkdirSync(join(workDir, "_generated"));
  writeFileSync(join(workDir, "_generated/api.d.ts"), generatedSource, "utf8");
  mkdirSync(join(workDir, "node_modules"));
  symlinkSync(
    resolve(repoRoot, "node_modules/zod"),
    join(workDir, "node_modules/zod"),
    "dir"
  );
  const typedGoodFile = join(workDir, "typed-good.tsx");
  const typedBadFile = join(workDir, "typed-bad.tsx");
  writeFileSync(join(workDir, "schemas.ts"), schemasSource, "utf8");
  writeFileSync(typedGoodFile, typedGoodSource, "utf8");
  writeFileSync(typedBadFile, typedBadSource, "utf8");
  return { typedGoodFile, typedBadFile };
}

function createTypedEslint(workDir) {
  return new ESLint({
    cwd: workDir,
    overrideConfigFile: true,
    overrideConfig: [
      {
        files: ["**/*.{ts,tsx}"],
        languageOptions: {
          parser: tsParser,
          parserOptions: {
            ecmaFeatures: { jsx: true },
            projectService: true,
            tsconfigRootDir: workDir,
          },
        },
      },
      createEslintConfig({ files: ["**/*.{ts,tsx}"] }),
    ],
  });
}

function assertParityRules(parityGood, parityBad, expectedRules) {
  assert.equal(
    parityGood.messages.length,
    0,
    `Expected 0 typed ESLint diagnostics on good.tsx, got: ${JSON.stringify(parityGood.messages)}`
  );
  const parityRuleIds = new Set(
    parityBad.messages.map((message) => message.ruleId)
  );
  for (const expected of expectedRules) {
    assert.ok(
      parityRuleIds.has(expected),
      `Expected typed ESLint to report ${expected}, got: ${[...parityRuleIds].join(", ")}`
    );
  }
}

async function verifyProgramEditInvalidation(workDir, typedBadFile) {
  const apiPath = join(workDir, "_generated/api.d.ts");
  writeFileSync(
    apiPath,
    generatedSource.replace(
      '"alpha" | "beta" | "stable"',
      '"canary" | "nightly" | "lts"'
    ),
    "utf8"
  );
  try {
    tsParser.clearCaches?.();
    const [afterEdit] = await createTypedEslint(workDir).lintFiles([
      typedBadFile,
    ]);
    assert.ok(
      !afterEdit.messages.some((message) =>
        message.message.includes("GeneratedReleaseChannel")
      ),
      `Expected edited program to drop stale GeneratedReleaseChannel union owner, got: ${JSON.stringify(afterEdit.messages)}`
    );
  } finally {
    writeFileSync(apiPath, generatedSource, "utf8");
    tsParser.clearCaches?.();
  }
}

async function verifySelfTypedRules(repoRoot) {
  const typedRulesConfig = createEslintConfig({ files: ["src/**/*.js"] });
  const typedRulesOnly = Object.fromEntries(
    typedRuleNames.map((name) => [`antidrift/${name}`, "error"])
  );
  const selfEslint = new ESLint({
    cwd: repoRoot,
    overrideConfigFile: true,
    overrideConfig: [
      {
        files: ["src/**/*.js"],
        languageOptions: {
          parser: tsParser,
          parserOptions: {
            projectService: {
              allowDefaultProject: ["src/*.js", "src/*/*.js", "src/*/*/*.js"],
              maximumDefaultProjectFileMatchCount_THIS_WILL_SLOW_DOWN_LINTING: 200,
            },
            tsconfigRootDir: repoRoot,
          },
        },
        plugins: typedRulesConfig.plugins,
        rules: typedRulesOnly,
      },
    ],
  });
  const selfResults = await selfEslint.lintFiles(["src/**/*.js"]);
  const selfMessages = selfResults.flatMap((lintReport) =>
    lintReport.messages.map(
      (diagnostic) =>
        `${lintReport.filePath}:${diagnostic.line} [${diagnostic.ruleId}] ${diagnostic.message}`
    )
  );
  assert.equal(
    selfMessages.length,
    0,
    `Expected 0 typed ESLint diagnostics on antidrift src/**/*.js, got: ${JSON.stringify(selfMessages)}`
  );
}

export async function runTypedEslintSmoke({
  workDir,
  repoRoot,
  goodFile,
  badFile,
  expectedRules,
  expectedDiagnostics,
}) {
  const { typedGoodFile, typedBadFile } = writeTypedProject(workDir, repoRoot);
  const eslint = createTypedEslint(workDir);
  const [typedGood, typedBad, parityGood, parityBad] = await eslint.lintFiles([
    typedGoodFile,
    typedBadFile,
    goodFile,
    badFile,
  ]);
  assert.equal(
    typedGood.messages.length,
    0,
    `Expected 0 typed ESLint diagnostics on typed-good.tsx, got: ${JSON.stringify(typedGood.messages)}`
  );
  assertReported(typedBad.messages, typedBadDiagnostics, "typed ESLint");
  assertParityRules(parityGood, parityBad, expectedRules);
  assertReported(parityBad.messages, expectedDiagnostics, "typed ESLint");
  await verifyProgramEditInvalidation(workDir, typedBadFile);
  await verifySelfTypedRules(repoRoot);
}
