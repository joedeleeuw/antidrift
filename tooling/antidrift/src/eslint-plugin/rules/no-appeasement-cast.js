import { inspectAppeasementCast } from "../../semantic-adapters/cast-proof.mjs";
import {
  missingTypeServicesVisitors,
  requireTypeServices,
} from "./type-services.js";

function isApprovedGeneratedCommentLine(rawLine) {
  const cleanedLine = rawLine.replace(/^\s*\*+\s*/u, "").trim();
  return (
    /^@generated(?:\b|$)/u.test(cleanedLine) ||
    (cleanedLine.startsWith("Code generated") &&
      cleanedLine.includes("DO NOT EDIT.")) ||
    cleanedLine.startsWith("This file was generated by") ||
    cleanedLine.startsWith("Generated by")
  );
}

function isDeclaredGeneratedFile(context) {
  const ast = context.sourceCode?.ast;
  const firstToken = ast
    ? context.sourceCode.getFirstToken(ast, { includeComments: false })
    : null;
  const comments = context.sourceCode?.getAllComments?.() ?? [];
  for (const comment of comments) {
    if (firstToken && comment.range[0] >= firstToken.range[0]) {
      break;
    }
    const commentLines = comment.value.split(/\r?\n/u);
    if (commentLines.some(isApprovedGeneratedCommentLine)) {
      return true;
    }
  }
  return false;
}

export function ruleNoAppeasementCast() {
  return {
    meta: {
      type: "problem",
      docs: {
        description:
          "Disallow casting any/unknown values into contracts without proof.",
      },
      schema: [],
    },
    create(context) {
      if (isDeclaredGeneratedFile(context)) {
        return {};
      }
      const services = requireTypeServices(context);
      if (!services) {
        return missingTypeServicesVisitors(context, "no-appeasement-cast");
      }
      const checker = services.program.getTypeChecker();
      return {
        TSAsExpression(node) {
          const decision = inspectAppeasementCast(node, services, checker);
          if (decision.action === "clear") {
            return;
          }
          if (decision.action === "incomplete") {
            context.report({
              node,
              message: decision.message,
            });
            return;
          }
          if (decision.action === "report") {
            context.report({
              node,
              message:
                "This cast forces an unproven value into a named contract. Declare the input type or use a type guard before assigning it.",
            });
          }
        },
      };
    },
  };
}
