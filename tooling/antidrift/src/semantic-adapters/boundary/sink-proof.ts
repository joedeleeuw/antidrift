import ts from "typescript";
import {
  ELEMENT,
  logicalOperators,
  unresolvedType,
} from "./boundary-contracts.ts";
import { typed } from "./boundary-types.ts";
import { excluded } from "./decision-cases.ts";
import { boundaryObservations } from "./boundary-observations.ts";
import { enclosingFunction, unwrapExpression } from "./boundary-syntax.ts";
import {
  declaredOperandType,
  narrowingProvesTarget,
} from "./narrowing-types.ts";
import { sameType } from "./type-difference.ts";
import type { Root } from "./root-domain.ts";
import type { TraceContext } from "./trace-context.ts";

export type SinkContext = Pick<
  TraceContext,
  "program" | "checker" | "observer" | "trace" | "contracts"
> &
  Pick<TraceContext["declarations"], "decode" | "unprovedNarrowing">;
export type UncheckedOptions = NonNullable<
  Parameters<TraceContext["contracts"]["claimContract"]>[1]
> & {
  readonly opaqueOnly?: boolean;
  readonly claimNode?: ts.Node;
};
function branchesOf(expression: ts.Expression) {
  if (ts.isConditionalExpression(expression)) {
    return [expression.whenTrue, expression.whenFalse];
  }
  if (
    ts.isBinaryExpression(expression) &&
    logicalOperators.has(expression.operatorToken.kind)
  ) {
    return [expression.left, expression.right];
  }
  return null;
}
export class SinkProof {
  readonly context: SinkContext;
  readonly rootFiles: ReadonlySet<string>;
  constructor(context: SinkContext) {
    this.context = context;
    this.rootFiles = new Set(context.program.getRootFileNames());
  }
  narrowingOccurred(node: ts.Expression): boolean {
    const unwrapped = unwrapExpression(node);
    const branches = branchesOf(unwrapped);
    if (branches) {
      return branches.every(
        (branch) =>
          !this.context.trace(branch).length || this.narrowingOccurred(branch)
      );
    }
    if (ts.isObjectLiteralExpression(unwrapped)) {
      return unwrapped.properties.every((property) => {
        if (ts.isPropertyAssignment(property)) {
          return (
            !this.context.trace(property.initializer).length ||
            this.narrowingOccurred(property.initializer)
          );
        }
        return (
          ts.isShorthandPropertyAssignment(property) &&
          this.narrowingOccurred(property.name)
        );
      });
    }
    if (ts.isArrayLiteralExpression(unwrapped)) {
      return unwrapped.elements.every((element) => {
        const spread = ts.isSpreadElement(element)
          ? element.expression
          : element;
        return (
          !this.context.trace(spread).length || this.narrowingOccurred(spread)
        );
      });
    }
    const flow = this.context.checker.getTypeAtLocation(unwrapped);
    const declared = declaredOperandType(this.context.checker, unwrapped, flow);
    return Boolean(declared) && !sameType(this.context.checker, declared, flow);
  }
  activeRoots(expression: ts.Expression): Root[] {
    const source = expression.getSourceFile();
    const preamble = source.text.slice(
      0,
      Math.min(source.statements[0]?.pos ?? 2048, 4096)
    );
    const generatedFile =
      /^\s*(?:\/\/|\/\*+|\*+)?\s*(?:@generated\b|Code generated .* DO NOT EDIT\.|This file was generated by\b|Generated by\b)/mu.test(
        preamble
      );
    if (excluded({ generatedFile })) {
      return [];
    }
    return this.context.trace(expression).filter(
      (root) =>
        !excluded({
          decoded: root.decoded,
          unopenedString: Boolean(root.activation),
          castChain: root.castChain,
        })
    );
  }
  demandedFields(target: ts.Type): ReadonlySet<string> | null {
    const nonNull = target.getNonNullableType();
    if (
      !(nonNull.flags & ts.TypeFlags.Object) ||
      this.context.checker.isArrayLikeType(nonNull) ||
      this.context.checker.getIndexInfosOfType(nonNull).length
    ) {
      return null;
    }
    const properties = this.context.checker.getPropertiesOfType(nonNull);
    return properties.length
      ? new Set(properties.map((property) => property.name))
      : null;
  }
  demandedBy(root: Root, target: ts.Type, options: UncheckedOptions): boolean {
    let contract: ts.Type | null | undefined = target;
    for (const step of root.path ?? []) {
      if (!contract) {
        return true;
      }
      if (step === ELEMENT) {
        contract = this.context.contracts.elementContract(contract);
        continue;
      }
      const demanded = this.demandedFields(contract);
      if (!demanded) {
        return true;
      }
      if (!demanded.has(step)) {
        return false;
      }
      contract = this.context.contracts.memberContract(contract, step);
    }
    if (
      !root.deep &&
      root.path?.length &&
      contract &&
      !unresolvedType(contract) &&
      !typed(contract, options)
    ) {
      return false;
    }
    const overrides = root.overrides;
    if (root.deep || !overrides || !contract) {
      return true;
    }
    const demanded = this.demandedFields(contract);
    if (!demanded) {
      return true;
    }
    return [...demanded].some((name) => !overrides.has(name));
  }
  pairCapCallback(node: ts.Node) {
    if (!this.context.observer.enabled) {
      return undefined;
    }
    return () => {
      this.context.observer.boundFired(
        boundaryObservations.bounds.narrowingProofPairCap,
        {
          call: ts.isCallExpression(node) ? node : null,
          declaration: enclosingFunction(node) ?? node,
        }
      );
    };
  }
  claimCovers(
    root: Root,
    target: ts.Type,
    claimNode: ts.Node | undefined,
    expression: ts.Expression
  ): boolean {
    const claim = root.claim;
    if (!claim || !claim.contract || claim.node === claimNode) {
      return false;
    }
    if (!this.rootFiles.has(claim.node.getSourceFile().fileName)) {
      return false;
    }
    if (unresolvedType(claim.contract)) {
      if (this.context.observer.enabled) {
        this.context.observer.claimCovered({
          claimNode: claim.node,
          claimContract: claim.contract,
          demandedContract: null,
          path: root.path,
          useExpression: expression,
        });
      }
      return true;
    }
    const demanded = this.context.contracts.projectContract(target, root.path);
    const typeParameterClaim = Boolean(
      claim.contract.flags & ts.TypeFlags.TypeParameter
    );
    if (typeParameterClaim && this.context.unprovedNarrowing(expression)) {
      return false;
    }
    const claimed = typeParameterClaim
      ? this.context.contracts.projectContract(
          this.context.checker.getTypeAtLocation(expression),
          root.path
        )
      : claim.contract;
    const covered = Boolean(
      demanded &&
      claimed &&
      (claimed.flags & ts.TypeFlags.TypeParameter
        ? this.context.contracts.claimContract(demanded, {
            allowTypeParameter: true,
          }) === claimed ||
          this.context.checker.isTypeAssignableTo(claimed, demanded)
        : narrowingProvesTarget(
            this.context.checker,
            claimed,
            demanded,
            this.pairCapCallback(claim.node)
          ))
    );
    if (covered && this.context.observer.enabled) {
      this.context.observer.claimCovered({
        claimNode: claim.node,
        claimContract: claim.contract,
        demandedContract: demanded,
        path: root.path,
        useExpression: expression,
      });
    }
    return covered;
  }
  unchecked(
    expression: ts.Expression,
    target: ts.Type | null | undefined,
    options: UncheckedOptions = {}
  ): Root[] {
    if (options.opaqueOnly) {
      if (
        !(
          this.context.checker.getTypeAtLocation(expression).flags &
          ts.TypeFlags.Any
        )
      ) {
        return [];
      }
      return this.activeRoots(expression).filter((root) =>
        Boolean(root.opaque)
      );
    }
    if (target && unresolvedType(target)) {
      return this.activeRoots(expression)
        .filter(
          (root) =>
            !excluded({
              claimed: this.claimCovers(
                root,
                target,
                options.claimNode,
                expression
              ),
            })
        )
        .map((root) => ({
          ...root,
          incomplete: root.incomplete ?? "unresolved contract type",
        }));
    }
    if (!target || excluded({ acceptsUnknown: !typed(target, options) })) {
      return [];
    }
    const roots = this.activeRoots(expression).filter(
      (root) =>
        !excluded({
          undemanded: !this.demandedBy(root, target, options),
          claimed: this.claimCovers(
            root,
            target,
            options.claimNode,
            expression
          ),
        })
    );
    if (!roots.length) {
      return [];
    }
    const proves = this.pathProves(expression, target);
    const intactCarrier =
      proves && roots.every((root) => root.pending && !root.incomplete);
    const narrowed = roots.every((root) =>
      this.rootNarrowed(root, expression, target)
    );
    if (excluded({ intactCarrier, narrowed })) {
      return [];
    }
    return roots;
  }
  pathProves(site: ts.Expression, target: ts.Type): boolean {
    const rawActual = this.context.checker.getTypeAtLocation(site);
    const actual = ts.isReturnStatement(site.parent)
      ? (this.context.checker.getAwaitedType(rawActual) ?? rawActual)
      : rawActual;
    return (
      Boolean(actual) &&
      narrowingProvesTarget(
        this.context.checker,
        actual,
        target,
        this.pairCapCallback(site)
      )
    );
  }
  propertySite(literal: ts.ObjectLiteralExpression, step: string) {
    const property = literal.properties.find(
      (candidate) =>
        !ts.isSpreadAssignment(candidate) &&
        this.context.contracts.propertyKey(candidate) === step
    );
    if (!property) {
      return null;
    }
    if (ts.isPropertyAssignment(property)) {
      return property.initializer;
    }
    return ts.isShorthandPropertyAssignment(property) ? property.name : null;
  }
  pathSite(
    expression: ts.Expression,
    path: readonly string[] | undefined,
    target: ts.Type
  ) {
    let site = expression;
    let contract: ts.Type | null | undefined = target;
    for (const step of path ?? []) {
      const literal = unwrapExpression(site);
      if (step === ELEMENT || !ts.isObjectLiteralExpression(literal)) {
        break;
      }
      const next = this.propertySite(literal, step);
      if (!next) {
        break;
      }
      site = next;
      contract =
        this.context.contracts.memberContract(contract, step) ?? contract;
    }
    return { site, contract };
  }
  rootNarrowed(
    root: Root,
    expression: ts.Expression,
    target: ts.Type
  ): boolean {
    const { site, contract } = this.pathSite(expression, root.path, target);
    return (
      this.pathProves(site, contract) &&
      !this.context.unprovedNarrowing(site) &&
      (!root.opaque || this.narrowingOccurred(site))
    );
  }
}
