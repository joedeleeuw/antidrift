import ts from "typescript";
import {
  ELEMENT,
  assertionKinds,
  logicalOperators,
  unresolvedType,
} from "./boundary-contracts.mjs";
import { broad, excluded, typed } from "./boundary-declarations.mjs";
import { boundaryObservations } from "./boundary-observations.mjs";
import {
  enclosingFunction,
  isAssertionChain,
  unwrapExpression,
} from "./boundary-syntax.mjs";
import {
  declaredOperandType,
  narrowingProvesTarget,
  sameType,
} from "./cast-narrowing-proof.mjs";

function branchesOf(expression) {
  if (ts.isConditionalExpression(expression)) {
    return [expression.whenTrue, expression.whenFalse];
  }
  if (
    ts.isBinaryExpression(expression) &&
    logicalOperators.has(expression.operatorToken.kind)
  ) {
    return [expression.left, expression.right];
  }
  return null;
}

export function boundarySinks({
  program,
  checker,
  observer,
  trace,
  decode,
  unprovedNarrowing,
  contracts,
}) {
  const {
    claimContract,
    elementContract,
    memberContract,
    projectContract,
    propertyKey,
  } = contracts;
  const rootFiles = new Set(program.getRootFileNames());

  function narrowingOccurred(node) {
    const unwrapped = unwrapExpression(node);
    if (!unwrapped) return false;
    const branches = branchesOf(unwrapped);
    if (branches) {
      return branches.every(
        (branch) => !trace(branch).length || narrowingOccurred(branch)
      );
    }
    if (ts.isObjectLiteralExpression(unwrapped)) {
      return unwrapped.properties.every((property) => {
        if (ts.isPropertyAssignment(property)) {
          return (
            !trace(property.initializer).length ||
            narrowingOccurred(property.initializer)
          );
        }
        return (
          ts.isShorthandPropertyAssignment(property) &&
          narrowingOccurred(property.name)
        );
      });
    }
    if (ts.isArrayLiteralExpression(unwrapped)) {
      return unwrapped.elements.every((element) => {
        const spread = ts.isSpreadElement(element)
          ? element.expression
          : element;
        return !trace(spread).length || narrowingOccurred(spread);
      });
    }
    const flow = checker.getTypeAtLocation(unwrapped);
    const declared = declaredOperandType(checker, unwrapped, flow);
    return Boolean(declared) && !sameType(checker, declared, flow);
  }

  function activeRoots(expression) {
    const source = expression.getSourceFile();
    const preamble = source.text.slice(
      0,
      Math.min(source.statements[0]?.pos ?? 2048, 4096)
    );
    const generatedFile =
      /^\s*(?:\/\/|\/\*+|\*+)?\s*(?:@generated\b|Code generated .* DO NOT EDIT\.|This file was generated by\b|Generated by\b)/mu.test(
        preamble
      );
    if (excluded({ generatedFile })) return [];
    return trace(expression).filter(
      (root) =>
        !excluded({
          decoded: root.decoded,
          unopenedString: Boolean(root.activation),
          castChain: root.castChain,
        })
    );
  }

  function demandedFields(target) {
    const nonNull = target.getNonNullableType();
    if (
      !(nonNull.flags & ts.TypeFlags.Object) ||
      checker.isArrayLikeType(nonNull) ||
      checker.getIndexInfosOfType(nonNull).length
    ) {
      return null;
    }
    const properties = checker.getPropertiesOfType(nonNull);
    return properties.length
      ? new Set(properties.map((property) => property.name))
      : null;
  }

  function demandedBy(root, target, options) {
    let contract = target;
    for (const step of root.path ?? []) {
      if (!contract) {
        return true;
      }
      if (step === ELEMENT) {
        contract = elementContract(contract);
        continue;
      }
      const demanded = demandedFields(contract);
      if (!demanded) {
        return true;
      }
      if (!demanded.has(step)) {
        return false;
      }
      contract = memberContract(contract, step);
    }
    if (
      !root.deep &&
      root.path?.length &&
      contract &&
      !unresolvedType(contract) &&
      !typed(contract, options)
    ) {
      return false;
    }
    if (root.deep || !root.overrides || !contract) {
      return true;
    }
    const demanded = demandedFields(contract);
    if (!demanded) {
      return true;
    }
    return [...demanded].some((name) => !root.overrides.has(name));
  }

  function pairCapCallback(node) {
    if (!observer.enabled) {
      return undefined;
    }
    return () => {
      observer.boundFired(boundaryObservations.bounds.narrowingProofPairCap, {
        call: ts.isCallExpression(node) ? node : null,
        declaration: enclosingFunction(node) ?? node,
      });
    };
  }

  function claimCovers(root, target, claimNode, expression) {
    const claim = root.claim;
    if (!claim || !claim.contract || claim.node === claimNode) {
      return false;
    }
    if (!rootFiles.has(claim.node.getSourceFile().fileName)) {
      return false;
    }
    if (unresolvedType(claim.contract)) {
      if (observer.enabled) {
        observer.claimCovered({
          claimNode: claim.node,
          claimContract: claim.contract,
          demandedContract: null,
          path: root.path,
          useExpression: expression,
        });
      }
      return true;
    }
    const demanded = projectContract(target, root.path);
    const typeParameterClaim = Boolean(
      claim.contract.flags & ts.TypeFlags.TypeParameter
    );
    if (typeParameterClaim && unprovedNarrowing(expression)) {
      return false;
    }
    const claimed = typeParameterClaim
      ? projectContract(checker.getTypeAtLocation(expression), root.path)
      : claim.contract;
    const covered =
      Boolean(demanded) &&
      Boolean(claimed) &&
      (claimed.flags & ts.TypeFlags.TypeParameter
        ? claimContract(demanded, { allowTypeParameter: true }) === claimed ||
          checker.isTypeAssignableTo(claimed, demanded)
        : narrowingProvesTarget(
            checker,
            claimed,
            demanded,
            pairCapCallback(claim.node)
          ));
    if (covered && observer.enabled) {
      observer.claimCovered({
        claimNode: claim.node,
        claimContract: claim.contract,
        demandedContract: demanded,
        path: root.path,
        useExpression: expression,
      });
    }
    return covered;
  }

  function unchecked(expression, target, options = {}) {
    if (options.opaqueOnly) {
      if (!(checker.getTypeAtLocation(expression)?.flags & ts.TypeFlags.Any)) {
        return [];
      }
      return activeRoots(expression).filter((root) => Boolean(root.opaque));
    }
    if (unresolvedType(target)) {
      return activeRoots(expression)
        .filter(
          (root) =>
            !excluded({
              claimed: claimCovers(root, target, options.claimNode, expression),
            })
        )
        .map((root) => ({
          ...root,
          incomplete: root.incomplete ?? "unresolved contract type",
        }));
    }
    if (excluded({ acceptsUnknown: !typed(target, options) })) {
      return [];
    }
    const roots = activeRoots(expression).filter(
      (root) =>
        !excluded({
          undemanded: !demandedBy(root, target, options),
          claimed: claimCovers(root, target, options.claimNode, expression),
        })
    );
    if (!roots.length) {
      return [];
    }
    const proves = pathProves(expression, target);
    const intactCarrier =
      proves && roots.every((root) => root.pending && !root.incomplete);
    const narrowed = roots.every((root) =>
      rootNarrowed(root, expression, target)
    );
    if (excluded({ intactCarrier, narrowed })) {
      return [];
    }
    return roots;
  }

  function pathProves(site, target) {
    const rawActual = checker.getTypeAtLocation(site);
    const actual = ts.isReturnStatement(site.parent)
      ? (checker.getAwaitedType(rawActual) ?? rawActual)
      : rawActual;
    return (
      Boolean(actual) &&
      narrowingProvesTarget(checker, actual, target, pairCapCallback(site))
    );
  }

  function propertySite(literal, step) {
    const property = literal.properties.find(
      (candidate) =>
        !ts.isSpreadAssignment(candidate) && propertyKey(candidate) === step
    );
    if (!property) {
      return null;
    }
    if (ts.isPropertyAssignment(property)) {
      return property.initializer;
    }
    return ts.isShorthandPropertyAssignment(property) ? property.name : null;
  }

  function pathSite(expression, path, target) {
    let site = expression;
    let contract = target;
    for (const step of path ?? []) {
      const literal = unwrapExpression(site);
      if (
        !literal ||
        step === ELEMENT ||
        !ts.isObjectLiteralExpression(literal)
      ) {
        break;
      }
      const next = propertySite(literal, step);
      if (!next) {
        break;
      }
      site = next;
      contract = memberContract(contract, step) ?? contract;
    }
    return { site, contract };
  }

  function rootNarrowed(root, expression, target) {
    const { site, contract } = pathSite(expression, root.path, target);
    return (
      pathProves(site, contract) &&
      !unprovedNarrowing(site) &&
      (!root.opaque || narrowingOccurred(site))
    );
  }

  function argumentType(call, index) {
    const signature = checker.getResolvedSignature(call);
    if (!signature) {
      return null;
    }
    const parameter =
      signature.parameters[Math.min(index, signature.parameters.length - 1)];
    if (!parameter) {
      return null;
    }
    const instantiated = checker.getTypeOfSymbolAtLocation(parameter, call);
    const declaredParameter = parameter.valueDeclaration;
    const declared =
      declaredParameter &&
      ts.isParameter(declaredParameter) &&
      declaredParameter.type &&
      checker.getTypeFromTypeNode(declaredParameter.type);
    const contract =
      broad(instantiated) && declared?.flags & ts.TypeFlags.TypeParameter
        ? (checker.getBaseConstraintOfType(declared) ?? instantiated)
        : instantiated;
    if (!declaredParameter?.dotDotDotToken) {
      return contract;
    }
    if (checker.isTupleType(contract)) {
      return checker.getTypeArguments(contract)[
        index - signature.parameters.length + 1
      ];
    }
    return checker.getIndexTypeOfType(contract, ts.IndexKind.Number);
  }

  function ownedByCastChain(expression) {
    let current = expression;
    while (
      current &&
      (ts.isParenthesizedExpression(current) || ts.isAwaitExpression(current))
    ) {
      current = current.expression;
    }
    return Boolean(current) && isAssertionChain(current);
  }

  function observeSink(sinkKind, sinkNode, expression, evaluate) {
    if (!observer.enabled) {
      return evaluate();
    }
    const decision = observer.beginSink(sinkKind, sinkNode, expression);
    return observer.finishSink(decision, evaluate());
  }

  function assertionSink(assertion) {
    if (
      isAssertionChain(assertion) ||
      assertionKinds.has(assertion.parent.kind)
    ) {
      return [];
    }
    return observeSink(
      boundaryObservations.sinks.assertion,
      assertion,
      assertion.expression,
      () =>
        unchecked(assertion.expression, checker.getTypeAtLocation(assertion), {
          allowTypeParameter: true,
          claimNode: assertion,
        })
    );
  }

  function declarationSink(declaration) {
    if (!declaration.initializer || ownedByCastChain(declaration.initializer)) {
      return [];
    }
    if (declaration.type) {
      return observeSink(
        boundaryObservations.sinks.declaration,
        declaration,
        declaration.initializer,
        () =>
          unchecked(
            declaration.initializer,
            checker.getTypeFromTypeNode(declaration.type),
            { claimNode: declaration }
          )
      );
    }
    if (
      ts.isObjectBindingPattern(declaration.name) ||
      ts.isArrayBindingPattern(declaration.name)
    ) {
      return observeSink(
        boundaryObservations.sinks.declaration,
        declaration,
        declaration.initializer,
        () => unchecked(declaration.initializer, null, { opaqueOnly: true })
      );
    }
    return [];
  }

  function assignmentSink(assignment) {
    if (
      assignment.operatorToken.kind !== ts.SyntaxKind.EqualsToken ||
      ownedByCastChain(assignment.right)
    ) {
      return [];
    }
    return observeSink(
      boundaryObservations.sinks.assignment,
      assignment,
      assignment.right,
      () =>
        unchecked(assignment.right, checker.getTypeAtLocation(assignment.left))
    );
  }

  function returnSink(statement) {
    if (!statement.expression || ownedByCastChain(statement.expression)) {
      return [];
    }
    const owner = enclosingFunction(statement);
    if (!owner?.type) {
      return [];
    }
    return observeSink(
      boundaryObservations.sinks.return,
      statement,
      statement.expression,
      () =>
        unchecked(
          statement.expression,
          checker.getAwaitedType(checker.getTypeFromTypeNode(owner.type)),
          { claimNode: owner }
        )
    );
  }

  function typeArgumentSink(call) {
    if (!call.typeArguments?.length) {
      return [];
    }
    return observeSink(
      boundaryObservations.sinks.typeArgument,
      call,
      call,
      () => {
        if (
          !checker.getResolvedSignature(call) ||
          decode(call) ||
          !trace(call).some((root) => root.root === call)
        ) {
          return [];
        }
        return unchecked(
          call,
          checker.getTypeFromTypeNode(call.typeArguments[0]),
          {
            allowTypeParameter: true,
            claimNode: call,
          }
        );
      }
    );
  }

  const sinks = {
    [ts.SyntaxKind.AsExpression]: assertionSink,
    [ts.SyntaxKind.TypeAssertionExpression]: assertionSink,
    [ts.SyntaxKind.VariableDeclaration]: declarationSink,
    [ts.SyntaxKind.BinaryExpression]: assignmentSink,
    [ts.SyntaxKind.ReturnStatement]: returnSink,
    [ts.SyntaxKind.CallExpression]: typeArgumentSink,
  };

  function uncheckedAt(node) {
    const sink = sinks[node.kind];
    return sink ? sink(node) : [];
  }

  function uncheckedArgument(argument) {
    const call = argument.parent;
    if (
      !call?.arguments?.includes(argument) ||
      !(ts.isCallExpression(call) || ts.isNewExpression(call)) ||
      ownedByCastChain(argument)
    ) {
      return [];
    }
    return observeSink(
      boundaryObservations.sinks.argument,
      argument,
      argument,
      () => {
        if (
          !checker.getResolvedSignature(call) ||
          (ts.isCallExpression(call) && decode(call))
        ) {
          return [];
        }
        return unchecked(
          argument,
          argumentType(call, call.arguments.indexOf(argument))
        );
      }
    );
  }

  return { uncheckedAt, uncheckedArgument };
}
