import { existsSync } from "node:fs";
import {
  basename,
  dirname,
  isAbsolute,
  join,
  matchesGlob,
  relative,
} from "node:path";

const PLATFORM_SUFFIXES = ["ios", "android", "native", "web", "electron"];
const PLATFORM_EXTS = [".ts", ".tsx", ".js", ".jsx", ".mts", ".cts"];

export function hasPlatformSibling(filename) {
  if (!filename || !filename.startsWith("/")) return false;
  const name = basename(filename);
  const stem = name.replace(
    /(?:\.(?:ios|android|native|web|electron))?\.[cm]?[jt]sx?$/u,
    ""
  );
  if (!stem || stem === name) return false;
  const dir = dirname(filename);
  for (const suffix of PLATFORM_SUFFIXES) {
    for (const ext of PLATFORM_EXTS) {
      const candidate = `${stem}.${suffix}${ext}`;
      if (candidate !== name && existsSync(join(dir, candidate))) {
        return true;
      }
    }
  }
  if (/\.(?:ios|android|native|web|electron)\.[cm]?[jt]sx?$/u.test(name)) {
    for (const ext of PLATFORM_EXTS) {
      const candidate = `${stem}${ext}`;
      if (candidate !== name && existsSync(join(dir, candidate))) {
        return true;
      }
    }
  }
  return false;
}

export const scopeProperties = {
  files: { type: "array", items: { type: "string" } },
  excludeFiles: { type: "array", items: { type: "string" } },
};

function scopePatterns(options, field) {
  if (typeof options !== "object" || options === null) {
    return undefined;
  }
  const patterns = Reflect.get(options, field);
  if (!Array.isArray(patterns)) {
    return undefined;
  }
  return patterns.filter((pattern) => typeof pattern === "string");
}

const IGNORED_PATH_RE =
  /(?:^|\/)(?:node_modules|dist|build|coverage|\.output|\.nitro|\.tanstack|\.sst|\.vinxi|\.next|\.expo|\.wrangler|_generated|__generated__|generated|\.agents|\.claude|\.sudocode|\.scratch|\.agent-sources|\.repos|src-tauri\/target|src-tauri\/gen)\/|\.(?:gen|generated|min|umd|bundle)\.[cm]?[jt]sx?$|\.d\.[cm]?ts$/u;

const GENERATED_HEADER_RE =
  /\b(?:@generated|auto-?generated|do not edit|code generated by)\b/iu;

const generatedHeaderCache = new WeakMap();

function hasGeneratedHeader(sourceCode) {
  if (!sourceCode || typeof sourceCode !== "object") return false;
  if (generatedHeaderCache.has(sourceCode)) {
    return generatedHeaderCache.get(sourceCode);
  }
  const firstStmtStart =
    sourceCode.ast?.body?.[0]?.range?.[0] ?? Number.POSITIVE_INFINITY;
  const comments = sourceCode.getAllComments?.() ?? [];
  let generated = false;
  for (const comment of comments) {
    const start = comment.range?.[0] ?? 0;
    const line = comment.loc?.start?.line ?? 99;
    if (start >= firstStmtStart || line > 5) break;
    if (GENERATED_HEADER_RE.test(comment.value ?? "")) {
      generated = true;
      break;
    }
  }
  generatedHeaderCache.set(sourceCode, generated);
  return generated;
}

export function ruleFilename(context) {
  return (context.filename ?? "").replaceAll("\\", "/");
}

export function isRuleFile(context, inferredScope) {
  const [options] = context.options ?? [];
  const filename = ruleFilename(context);
  if (IGNORED_PATH_RE.test(filename)) return false;
  if (hasGeneratedHeader(context.sourceCode)) return false;
  const cwd = context.cwd ?? process.cwd();
  const local = isAbsolute(filename)
    ? relative(cwd, filename).replaceAll("\\", "/")
    : filename;
  const matches = (pattern) =>
    matchesGlob(local, pattern) || matchesGlob(filename, pattern);
  const files = scopePatterns(options, "files");
  const excludeFiles = scopePatterns(options, "excludeFiles") ?? [];
  return (
    (files === undefined || files.some(matches)) &&
    (files !== undefined || inferredScope?.(filename) !== false) &&
    !excludeFiles.some(matches)
  );
}
